package ru.study.flakyradar.analysis;

/** Решение для CI по прогону. */
public enum GateDecision {
    /** Падений нет. */
    PASS,
    /** Упали только известные флаки или тесты в карантине, либо кто-то прошёл лишь после повтора. CI не блокируем. */
    WARN,
    /** Есть новые падения или давно сломанные тесты вне карантина. CI должен упасть. */
    FAIL
}

package ru.study.flakyradar.analysis;

/** Вердикт по упавшему результату теста. */
public enum Verdict {
    /** Тест раньше был стабилен (или новый): вероятная регрессия, нужно смотреть. */
    NEW_FAILURE,
    /** Тест известен как нестабильный: падение, скорее всего, не связано с изменениями. */
    KNOWN_FLAKY,
    /** Тест падает уже несколько прогонов подряд на этой ветке: сломан давно. */
    LONG_BROKEN
}

-- Ядро Flaky Radar: проекты, прогоны, тесты, результаты, подписи ошибок, карантин.

create table project
(
    id             bigint generated by default as identity primary key,
    project_key    varchar(64)              not null unique,
    name           varchar(255)             not null,
    api_key_hash   varchar(64)              not null,
    created_at     timestamp with time zone not null
);

create table test_run
(
    id          bigint generated by default as identity primary key,
    project_id  bigint                   not null references project (id) on delete cascade,
    branch      varchar(255)             not null,
    commit_sha  varchar(64)              not null,
    attempt     integer                  not null,
    ci_run_id   varchar(128),
    build_url   varchar(1024),
    received_at timestamp with time zone not null,
    total       integer                  not null,
    passed      integer                  not null,
    failed      integer                  not null,
    skipped     integer                  not null,
    decision    varchar(16)              not null,
    constraint uq_test_run_ci unique (project_id, ci_run_id, attempt)
);

create index idx_test_run_project_commit on test_run (project_id, commit_sha);
create index idx_test_run_project_branch on test_run (project_id, branch, id desc);

-- для батч-вставки нужны последовательности: IDENTITY отключает батчинг в Hibernate
create sequence test_case_seq increment by 50;

create table test_case
(
    id          bigint primary key default nextval('test_case_seq'),
    project_id  bigint                   not null references project (id) on delete cascade,
    suite       varchar(1024)            not null,
    name        varchar(1024)            not null,
    full_name   varchar(2048)            not null,
    flaky       boolean                  not null default false,
    flip_count  integer                  not null default 0,
    last_status varchar(16),
    first_seen  timestamp with time zone not null,
    last_seen   timestamp with time zone not null,
    constraint uq_test_case_name unique (project_id, full_name)
);

create table failure_signature
(
    id              bigint generated by default as identity primary key,
    project_id      bigint                   not null references project (id) on delete cascade,
    hash            varchar(64)              not null,
    exception_type  varchar(512),
    normalized_text text                     not null,
    sample_message  text,
    occurrences     integer                  not null,
    first_seen      timestamp with time zone not null,
    last_seen       timestamp with time zone not null,
    constraint uq_signature_hash unique (project_id, hash)
);

create sequence test_result_seq increment by 50;

create table test_result
(
    id                bigint primary key default nextval('test_result_seq'),
    run_id            bigint      not null references test_run (id) on delete cascade,
    test_case_id      bigint      not null references test_case (id) on delete cascade,
    status            varchar(16) not null,
    duration_ms       bigint      not null,
    failed_attempts   integer     not null default 0,
    message           text,
    signature_id      bigint references failure_signature (id) on delete set null,
    verdict           varchar(16),
    quarantined       boolean     not null default false
);

create index idx_test_result_case_run on test_result (test_case_id, run_id desc);
create index idx_test_result_run on test_result (run_id);
create index idx_test_result_signature on test_result (signature_id);

create table quarantine
(
    id           bigint generated by default as identity primary key,
    project_id   bigint                   not null references project (id) on delete cascade,
    test_case_id bigint                   not null references test_case (id) on delete cascade,
    reason       varchar(1024)            not null,
    created_by   varchar(255),
    created_at   timestamp with time zone not null,
    expires_at   timestamp with time zone,
    removed_at   timestamp with time zone
);

-- у теста не больше одной активной записи карантина
create unique index uq_quarantine_active on quarantine (test_case_id) where removed_at is null;
